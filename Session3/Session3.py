
import numpy as np
import matplotlib.pyplot as plt

# Task 1: Simple Generator
def simple_generator(random_vector):
    """
    Generate a fake 28x28 grayscale image.
    Pixel values are between 0 and 1.
    """
    random_vector = np.asarray(random_vector)
    np.random.seed(int(abs(random_vector[0]) * 1000) % 10000)

    image = np.random.rand(28, 28)
    return image


# Task 2: Simple Discriminator
class Discriminator:
    def discriminate(self, image):
        """
        Return a score between 0 and 1.
        Higher score means more likely to be real.
        This is a simple illustrative rule, not a trained model.
        """
        image = np.asarray(image)

        if image.shape != (28, 28):
            raise ValueError("Image must have shape 28x28.")

        mean_pixel = np.mean(image)

        # Simple heuristic: brighter images are considered more real
        if mean_pixel > 0.5:
            return 0.8
        else:
            return 0.2


# Task 3: Simulate one adversarial training cycle
random_vector = np.random.randn(10)

fake_image = simple_generator(random_vector)

discriminator = Discriminator()
score = discriminator.discriminate(fake_image)

print("Discriminator score:", score)

# A score above 0.5 predicts real; otherwise predicts fake
prediction = "real" if score > 0.5 else "fake"

print("Discriminator prediction:", prediction)

if prediction == "fake":
    print("Correct! The Discriminator identified the fake image.")
else:
    print("Incorrect! The Discriminator classified the fake image as real.")

# Display generated image
plt.imshow(fake_image, cmap="gray", vmin=0, vmax=1)
plt.title("Fake Image Generated by simple_generator()")
plt.axis("off")
plt.show()
